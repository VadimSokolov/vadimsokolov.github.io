"""Collect the results of Polson and Sokolov, "GBC versus GANs" (Nov 2026) for gbc-lab.html.

Reads the res_*.json files written by the paper's exp.py, exp2.py, exp3.py and exp4.py and
writes gbc-gan-data.js: per-experiment means and standard deviations over seeds, training
curves, and seed-0 samples (subsampled) for the plots in Part III of the lab.

Usage: python gbc-gan-extract.py /path/to/gbc_vs_gan_for_vadim [--out gbc-gan-data.js]
"""
import argparse
import json
import os

import numpy as np


def summ(rows, keys):
    return {k: [round(float(np.mean([r[k] for r in rows])), 4), round(float(np.std([r[k] for r in rows], ddof=1)), 4)] for k in keys}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("--out", default="gbc-gan-data.js")
    a = ap.parse_args()
    J = lambda n: json.load(open(os.path.join(a.src, f"res_{n}.json")))
    rng = np.random.default_rng(0)
    sub = lambda x, n: np.round(np.asarray(x)[rng.choice(len(x), size=min(n, len(x)), replace=False)], 3).tolist()
    out = {}

    d = J("post")
    out["post"] = {m: {"tab": summ([s[0] for s in d[m]], ["w1_0.25", "w1_1.0", "w1_2.0", "ks_pit", "cov90"]),
                       "curves": [[round(c["w1"], 4) for c in s[1]] for s in d[m]], "val": [round(c.get("val", float("nan")), 4) for c in d[m][0][1]],
                       "steps": [c["step"] for c in d[m][0][1]], "samp": {y: sub(d[m][0][2][y], 3000) for y in ["0.25", "1.0", "2.0"]}} for m in ["GBC", "GAN"]}
    d = J("ring")
    out["ring"] = {m: {"tab": summ([s[0] for s in d[m]], ["modes", "hq", "kl", "sw1"]), "modes": [[c["modes"] for c in s[1]] for s in d[m]],
                       "steps": [c["step"] for c in d[m][0][1]], "samp": sub(d[m][0][2], 2000)} for m in ["GBC", "GAN"]}
    d = J("grid")
    out["grid"] = {m: {"tab": summ(d[m], ["modes", "hq", "kl", "sw1"]), "samp": sub(d[m + "_samples"], 2500)} for m in ["GBC", "GAN"]}
    d = J("sweep")
    out["sweep"] = {k: summ(v, ["modes", "hq", "kl", "sw1"]) for k, v in d.items()}
    d = J("nig")
    out["nig"] = {m: summ(d[m], ["w1_mu", "w1_logsig", "width_mu", "width_logsig", "cov_mu", "cov_logsig", "energy"]) for m in ["GBC", "GAN"]}
    d = J("gk")
    out["gk"] = {m: summ(d[m], [f"{s}_{p}" for s in ["cov", "rmse", "crps"] for p in "abgk"]) for m in ["GBC", "GAN"]}
    d = J("beta")
    out["beta"] = {m: {"q7": [np.round(r["q7"], 3).tolist() for r in d[m]], "err": [round(r["err"], 4) for r in d[m]]} for m in ["GBC", "GAN"]}

    with open(a.out, "w") as f:
        f.write("// Generated by gbc-gan-extract.py from the result files of Polson and Sokolov, GBC versus GANs (2026); do not edit by hand.\nwindow.GBC_GAN = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", a.out, os.path.getsize(a.out), "bytes")
    for e in ["post", "ring", "grid"]:
        for m in ["GBC", "GAN"]:
            print(e, m, {k: v for k, v in (out[e][m]["tab"]).items()})
    for m in ["GBC", "GAN"]:
        print("nig", m, out["nig"][m]); print("gk", m, out["gk"][m])
    print("sweep", out["sweep"])


if __name__ == "__main__":
    main()
